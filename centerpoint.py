def generate_heatmap(w,h, centers,sigma):

  x_axis = torch.arange(0, w, device=centers.device, dtype=torch.float32)
  y_axis = torch.arange(0, h, device=centers.device, dtype=torch.float32)
  y_grid, x_grid = torch.meshgrid(y_axis, x_axis, indexing='ij')

  distances_squared = torch.zeros((w,h), device=centers.device)

  for i in range(centers.shape[0]):
    distances_squared += (x_grid-centers[i][0])**2 + (y_grid-centers[i][1])**2

  heatmap = torch.exp(-1*distances_squared/(2*sigma**2))

  return heatmap

class CenterPoint_FirstStage(nn.Module): 
#input is assumed to be of shape [C,W,H]
  def __init__(self, w, h, C, num_classes, K, hidden_channels=64, stride = 2, pc_range = [-51.2, 51.2], in_dims = 512):
    super().__init__()

    self.w = w
    self.h = h
    self.num_classes = num_classes
    self.C = C
    self.K = K #K is max number of centers per heatmap layer
    self.stride = stride
    self.range = pc_range
    self.in_dims = in_dims

    self.shared = nn.Sequential(nn.Conv2d(self.C, hidden_channels, kernel_size = 3, padding = 1, bias = True), nn.ReLU())

    self.heat_conv = nn.Conv2d(hidden_channels, num_classes, kernel_size = 1, stride = self.stride)

    self.offset = nn.Conv2d(hidden_channels, 2, kernel_size = 1)             # (δx, δy)
    self.z = nn.Conv2d(hidden_channels, 1, kernel_size = 1)             # z center
    self.size = nn.Conv2d(hidden_channels, 3, kernel_size = 1)             # log(w, l, h)
    self.yaw = nn.Conv2d(hidden_channels, 2, kernel_size = 1)             # (sin θ, cos θ)
    #self.velocity = nn.Conv2d(hidden_channels, 2, kernel_size = 1)

    nn.init.constant_(self.heat_conv.bias, -2.19)


  def learn_heatmap(self, shared):

    raw_logits = self.heat_conv(shared).permute(1,2,0)
    heatmap = F.sigmoid(raw_logits)

    return heatmap, raw_logits

  def get_shared_feats(self, feature_map):
    return self.shared(feature_map)

  def get_centers(self, heatmap):                      # heatmap: [H, W, Ncls]
    heat = heatmap.detach().permute(2, 0, 1).unsqueeze(0)          # [1, Ncls, H, W]
    hmax = F.max_pool2d(heat, kernel_size=3, stride=1, padding=1) 

    peaks = heat * (hmax == heat)                                  
    Ncls, H, W = heat.shape[1:]
    scores, idx = peaks.view(Ncls, -1).topk(self.K, dim=1) # [1, Ncls, H*W]

    rows, cols = idx // W, idx % W
    cls = torch.arange(Ncls, device=heat.device).unsqueeze(1).expand(-1, self.K) #[Ncls, K]
    
    return rows.reshape(-1), cols.reshape(-1), scores.reshape(-1), cls.reshape(-1)

  def regression_heads(self, shared_feats):

    offset = self.offset(shared_feats).permute(1,2,0)
    z = self.z(shared_feats).squeeze()
    size = self.size(shared_feats).permute(1,2,0)
    yaw = self.yaw(shared_feats).permute(1,2,0)
    #velocity = self.velocity(shared_feats).permute(1,2,0)

    return offset, z, size, yaw

  def forward(self, feature_map):
    shared = self.get_shared_feats(feature_map)

    heatmap, raw_logits = self.learn_heatmap(shared)

    offset, z, size, yaw = self.regression_heads(shared)

    size = size.clamp(min = -4, max = 4)
    regression_maps = [offset, size, z, yaw]

    rows, cols, scores, cls = self.get_centers(heatmap)
    r, c = rows * self.stride, cols * self.stride

    span = self.range[1] - self.range[0]
    x = ((r.float() / self.in_dims - 0.5) * span).clamp(self.range[0], self.range[1])
    y = ((c.float() / self.in_dims - 0.5) * span).clamp(self.range[0], self.range[1])

    ctr = torch.stack([x, y], dim=1) + offset[r, c]                # keeps gradient
    out = torch.cat([size[r, c], yaw[r, c], ctr,
                     z[r, c].detach().unsqueeze(1),
                     cls.unsqueeze(1).to(ctr.dtype),
                     scores.unsqueeze(1).to(ctr.dtype)], dim=1)    # [N, 10]

    return heatmap, out, regression_maps, shared, raw_logits

class CenterPoint_SecondStage(nn.Module):

  def __init__(self, w, h, C, num_classes, hidden_channels = 32, max_log_delta = 0.5, pc_range = [-51.2, 51.2]): #C is C of shared map

    super().__init__()

    self.w = w
    self.max_log_delta = max_log_delta
    self.pc_range = pc_range
    self.h = h
    self.C =C
    self.num_classes = num_classes

    self.shared = nn.Sequential(nn.Linear(5*C, hidden_channels, bias = True), nn.BatchNorm1d(num_features=hidden_channels),
                                        nn.ReLU())

    self.refine_network = nn.Linear(hidden_channels,7)

    self.confidence_network = nn.Linear(hidden_channels,1)

    nn.init.zeros_(self.refine_network.weight)
    nn.init.zeros_(self.refine_network.bias)

  def get_box_points(self, boxes):
    lw = boxes[:, 0:2].exp()                                   
    heading = F.normalize(boxes[:, [4, 3]], dim=-1)            # (cos, sin), unit norm
    cos, sin = heading[:, 0], heading[:, 1]

    center = boxes[:, 5:7]                                     # (N, 2)
    fwd = torch.stack([cos, sin], dim=-1)                      # along length, (N, 2)
    side = torch.stack([-sin, cos], dim=-1)                    # along width, (N, 2)

    off_l = fwd * (lw[:, 0:1] * 0.5)    
    off_w = side * (lw[:, 1:2] * 0.5)

    return torch.stack(
        [center, center + off_l, center - off_l, center + off_w, center - off_w],
        dim=1,
    )

  def BEV_sample(self, box_centers, shared_map): #box centers should be batched - [N, 5, 2]

    C = self.C
    N = box_centers.shape[0]
    min_x, max_x = self.pc_range
    min_y, max_y = self.pc_range

    normalized_x = 2.0 *((box_centers[...,0]-min_x)/(max_x-min_x)) - 1.0
    normalized_y = 2.0 *((box_centers[...,1]-min_y)/(max_y-min_y)) - 1.0

    normalized_centers = torch.stack([normalized_x, normalized_y], dim = -1).unsqueeze(0).to(shared_map.dtype) #[1, N, 5, 2]

    sampled = F.grid_sample(
        shared_map.unsqueeze(0), normalized_centers,
        mode="bilinear", padding_mode="zeros", align_corners=False,
    )                                                          # (1, C, N, 5)

    return sampled.squeeze(0).permute(1,2,0).reshape(N, 5*C)

  def refine_boxes(self, sampled_centers, original_boxes):

    sampled_centers = sampled_centers.detach()
    out_shared = self.shared(sampled_centers)

    out_refine = self.refine_network(out_shared) #unclamped for training
    out_I = self.confidence_network(out_shared).squeeze(-1)

    with torch.no_grad(): #only for inference, not needed in training
      d = out_refine.detach()
      dlog = d[:, 0:3].clamp(-self.max_log_delta, self.max_log_delta)
      dyaw = d[:, 3]
      dxyz = d[:, 4:7]

      norm_yaws = F.normalize(original_boxes[:, [3,4]], dim  = -1)
      sin0, cos0 = norm_yaws[:, 0], norm_yaws[:, 1]
      dsin, dcos = torch.sin(dyaw), torch.cos(dyaw)

      out = original_boxes.clone()

      out[:, 0:3] += dlog
      out[:, 5:8] += dxyz

      out[:, 3] = sin0 * dcos + cos0 * dsin    #sin(a + d)
      out[:, 4] = cos0 * dcos - sin0 * dsin      # cos(a + d)
      out[:, 9] = torch.sqrt((torch.sigmoid(out_I.detach()) * original_boxes[:, 9]).clamp(min = 0))

    return out, out_refine, out_I #out_I are raw logits, to be passed to training. I scores in out are processed through sigmoid
  
  def forward(self, centers_in, shared_map):

    centers_sampled = self.get_box_points(centers_in)

    out_feats = self.BEV_sample(centers_sampled, shared_map)

    out, d_vec_out, I_out = self.refine_boxes(out_feats, centers_in)

    return out, d_vec_out, I_out

class CenterPoint(nn.Module):

  def __init__(self, w, h, C, num_classes, K=10, hidden_channels = [64, 32], threshold = 0.45, stride = 2, max_det = 100):

    super().__init__()

    self.w = w
    self.h = h
    self.C =C
    self.num_classes = num_classes
    self.K = K
    self.threshold = threshold
    self.stride = stride
    self.max_det = max_det

    self.hidden_channels1 = hidden_channels[0]
    self.hidden_channels2 = hidden_channels[1]

    self.stage1 = CenterPoint_FirstStage(self.w, self.h, self.C, self.num_classes, self.K, hidden_channels = self.hidden_channels1, stride = self.stride)
    self.stage2 = CenterPoint_SecondStage(self.w, self.h, self.hidden_channels1, self.num_classes, hidden_channels = self.hidden_channels2)

  def NMS(self, centers, threshold, init_thresh = 0.1): #uses estimated BEV coords

    tm = centers[:, 9] > init_thresh
    centers = centers[tm]
    if centers.shape[0] == 0:
        return centers

    l, w = centers[:, 0].clamp(-4, 4).exp().clamp(min=0.1), centers[:, 1].clamp(-4, 4).exp().clamp(min=0.1)
    yaw = torch.atan2(centers[:, 3], centers[:, 4])
    cos, sin = yaw.cos().abs(), yaw.sin().abs()

    hx = 0.5 * (l * cos + w * sin)
    hy = 0.5 * (l * sin + w * cos)

    cx, cy = centers[:, 5], centers[:, 6]
    bev_coords = torch.stack([cx-hx, cy-hy, cx+hx, cy+hy], dim = 1)

    keep = torchvision.ops.batched_nms(bev_coords, centers[:, 9], centers[:, 8].long(), threshold)

    return centers[keep[:self.max_det]]

  def forward(self, feat_map):

    heatmap, centers, regression_maps, shared_map, raw_logits = self.stage1(feat_map)

    updated_centers, d_vecs, I = self.stage2(centers, shared_map)

    out = self.NMS(updated_centers, self.threshold)

    return out, centers, d_vecs, I, regression_maps, raw_logits
