def global_augmentation(points, boxes, rotation_range = [-np.pi/4, np.pi/4], scale_range = [0.95,1.05], translate_stdev = .2):
  new_boxes = []

  theta = np.random.uniform(rotation_range[0], rotation_range[1])
  scale = np.random.uniform(scale_range[0], scale_range[1])
  translation = np.random.normal(0, translate_stdev, size = 3)
  x_flip = np.random.rand()
  y_flip = np.random.rand()

  rot_matrix = np.array([[np.cos(theta),-np.sin(theta), 0],[np.sin(theta),np.cos(theta),0],[0,0,1]])

  rot_quat = Quaternion(matrix=rot_matrix)

  points[:, :3] = points[:, :3] @ rot_matrix
  points[:, :3] *= scale
  points[:, :3] += translation

  for box in boxes:
    box.rotate(rot_quat)
    box.center *= scale
    box.wlh *= scale
    box.center += translation

  if x_flip > 0.5:
    points[:, 0] *= -1
    for box in boxes:
      box.center[0] *= -1
      alpha = get_yaw(box.orientation)
      new_alpha = np.pi-alpha
      box.orientation = Quaternion(axis=[0, 0, 1], radians=new_alpha)

  if y_flip > 0.5:
    points[:, 1] *= -1
    for box in boxes:
      box.center[1] *= -1
      alpha = get_yaw(box.orientation)
      new_alpha = -alpha
      box.orientation = Quaternion(axis=[0, 0, 1], radians=new_alpha)

