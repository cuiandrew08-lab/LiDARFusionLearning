def IoU(center_a0, center_b0):

    center_a = center_a0.clone().detach().cpu()
    center_b = center_b0.clone().detach().cpu()

    l_a, w_a, h_a = center_a[0], center_a[1], center_a[2]
    x_a, y_a, z_a = center_a[5], center_a[6], center_a[7]
    sin_a, cos_a = center_a[3], center_a[4]

    l_b, w_b, h_b = center_b[0], center_b[1], center_b[2]
    x_b, y_b, z_b = center_b[5], center_b[6], center_b[7]
    sin_b, cos_b = center_b[3], center_b[4]

    scale_a = np.exp(np.array([l_a, w_a, h_a]))
    scale_b = np.exp(np.array([l_b, w_b, h_b]))

    translation_a = np.array([x_a, y_a, z_a])
    translation_b = np.array([x_b, y_b, z_b])

    rotation_a = np.array([[cos_a, -1*sin_a,0],[sin_a, cos_a,0],[0,0,1]])
    rotation_b = np.array([[cos_b, -1*sin_b,0],[sin_b, cos_b,0],[0,0,1]])

    box_a = BoxIoU.from_transformation(rotation_a, translation_a, scale_a)
    box_b = BoxIoU.from_transformation(rotation_b, translation_b, scale_b)

    iou = IoU3d(box_a, box_b)

    return iou.iou()

def boxes_to_tensor(boxes):

  boxes_tensor = []

  for box in boxes:
    center = torch.from_numpy(box.center)
    alpha = box.orientation.radians
    size = torch.from_numpy(box.wlh)

    rotation = torch.tensor([np.sin(alpha), np.cos(alpha)])

    boxes_tensor.append(torch.cat([size, rotation, center]))

  boxes_tensor = torch.stack(boxes_tensor)

  return boxes_tensor