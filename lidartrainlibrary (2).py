def process_boxes(nusc, sample, boxes, cloud, threshold = 1):

  ego_pose = nusc.get("ego_pose", sample["data"]["LIDAR_TOP"])

  sd_rec = nusc.get('sample_data', sample['data']['LIDAR_TOP'])
  cal_sensor = nusc.get('calibrated_sensor', sd_rec['calibrated_sensor_token'])

  out_boxes = []

  valid_boxes = []

  cloud_xyz = cloud[:,:3].T

  for box in boxes:
    category_name = box.name

    detection_name = category_to_detection_name(category_name)

    box.translate(-np.array(ego_pose['translation']))
    box.rotate(Quaternion(ego_pose['rotation']).inverse)

    box.translate(-np.array(cal_sensor['translation']))
    box.rotate(Quaternion(cal_sensor['rotation']).inverse)

    box.name = detection_name

    out_boxes.append(box)

  for box in out_boxes:
      indices = points_in_box(box, cloud_xyz)
      num_pts = np.sum(indices)

      if num_pts >= threshold and box.name != None:

        label = category_to_label(box.name)
        box.label = label

        valid_boxes.append(box)

  return valid_boxes

def splat_gaussian(heatmap, center, sigma):

  r = heatmap.shape[0]

  x_axis = torch.arange(0, r, device=heatmap.device, dtype=torch.float32)
  y_axis = torch.arange(0, r, device=heatmap.device, dtype=torch.float32)
  y_grid, x_grid = torch.meshgrid(y_axis, x_axis, indexing='ij')

  distances_squared = torch.zeros((r,r), device=heatmap.device)

  distances_squared += (x_grid-center[0])**2 +(y_grid-center[1])**2

  gaussian = torch.exp((-1*distances_squared)/(2*sigma**2))

  outmap = np.maximum(heatmap, gaussian)

  return outmap

def gaussian_radius(w, l, threshold = 0.1):

    a1, b1, c1 = 4, -2*(w+l), (1-threshold)*w*l
    r1 = (b1 - np.sqrt(b1**2 - 4*a1*c1)) / (2*a1)

    a2, b2, c2 = 4*threshold, 2*threshold*(w+l), -(1-threshold)*w*l
    r2 = (-b2 + np.sqrt(b2**2 - 4*a2*c2)) / (2*a2)

    a3, b3, c3 = 1, -(w+l), (1-1/threshold)*w*l
    r3 = (b3 + np.sqrt(b3**2 - 4*a3*c3)) / (2*a3)

    return max(min(r1, r2, r3),2)


def target_generation(gt_boxes, heatmap_resolution = 256, threshold = 0.1, k =10, stride = 2, pc_range = [-51.2, -51.2, 51.2, 51.2], max_objects = 500): 

  box_ij = []
  box_wl = []

  #x_min, y_min, x_max, y_max = pc_range
  x_min, y_min, x_max, y_max, _, _ = get_boxes_max_min(gt_boxes)

  for box in gt_boxes:

    box_x = box.center[0]
    box_y = box.center[1]

    i = np.floor((box_x - x_min)/(x_max - x_min) * (heatmap_resolution - 1))
    j = np.floor((box_y - y_min)/(y_max - y_min) * (heatmap_resolution - 1))

    i = int(i)
    j = int(j)

    box_ij.append([i,j])
    box_wl.append([box.wlh[0], box.wlh[1]])

  sigmas = []

  for i in range(len(box_wl)):
    w = box_wl[i][0]
    l = box_wl[i][1]

    sigma = gaussian_radius(w, l, threshold = threshold)

    sigmas.append(sigma)

  out_heatmaps = torch.zeros((heatmap_resolution, heatmap_resolution, k))

  target_resolution = heatmap_resolution * stride

  offset_target = torch.zeros((target_resolution, target_resolution, 2))
  size_target = torch.zeros((target_resolution, target_resolution, 3))
  z_target = torch.zeros((target_resolution, target_resolution))
  rotation_target = torch.zeros((target_resolution, target_resolution, 2))

  ind = torch.zeros((max_objects))
  mask = torch.zeros((max_objects))
  cat = torch.zeros((max_objects))

  for m in range(len(box_ij)):
    i, j = box_ij[m]

    i, j = i*stride, j*stride
    box = gt_boxes[m]

    if not (0 <= i < target_resolution and 0 <= j < target_resolution):
      continue

    label = box.label

    label_map = out_heatmaps[:,:,label]

    out_heatmaps[:,:,label] = splat_gaussian(label_map, box_ij[m], sigmas[m])

    box_i = (i / (target_resolution - 1) * (x_max - x_min)) + x_min
    box_j = (j / (target_resolution - 1) * (y_max - y_min)) + y_min

    offset_x = box.center[0] - box_i
    offset_y = box.center[1] - box_j
    offset_m = torch.tensor([offset_x, offset_y])

    size_m = torch.log(torch.tensor(box.wlh))

    z_m = box.center[2]

    alpha = box.orientation.radians

    rotation_m = torch.tensor([np.sin(alpha), np.cos(alpha)])

    offset_target[i][j] = offset_m
    size_target[i][j] = size_m
    z_target[i][j] = z_m
    rotation_target[i][j] = rotation_m

    if m < max_objects:
    
      ind[m] = j * target_resolution + i
      mask[m] = 1
      mask[m-1] = 0
      cat[m] = label

  return out_heatmaps, offset_target, size_target, z_target, rotation_target, ind, mask, cat

def loss_hm(heatmap, targetmap, alpha = 2, beta = 4):
  loss_hm = 0

  N = heatmap[heatmap == 1].shape[0]

  for i in range(heatmap.shape[0]):
    for j in range(heatmap.shape[1]):

      if targetmap[i][j] == 1:
        loss_ij = ((1-heatmap[i][j])**alpha)*torch.log(heatmap[i][j])

      else:
        loss_ij = ((1-targetmap[i][j])**beta) * (heatmap[i][j]**alpha) * torch.log(1-heatmap[i][j])

      loss_hm += loss_ij

  return loss_hm * -1 /N

